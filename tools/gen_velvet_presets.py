"""VELVET MOTION factory sounds -> firmware/src/velvet_presets.h (the VELVET engine's presets).

    tools/gen_velvet_presets.py SOUNDS.json [OUT.h]

SOUNDS.json is the dump of the desktop plugin's factory library (one object per sound: its engine, the
shared knobs in "values", per-engine settings). Only the four engines this firmware has are used: Soul Keys,
Funk Bass (not FM Bass), Velvet Synths and Soul Organ. The header is committed, so a normal build does not
need the plugin's files. The registration table below must match VLV_REG in eng_velvet.c.
"""
import json, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REG = [[0,0,8,0,0,0,0,0,0],[0,0,8,4,0,0,0,0,0],[6,2,8,4,2,1,0,0,0],[8,8,8,0,0,0,0,0,0],
       [8,0,8,8,0,0,0,0,4],[8,6,8,6,4,4,2,0,0],[8,8,8,6,5,4,3,2,2],[8,8,8,8,8,8,8,8,8]]
QUOTA = {"EP": 16, "BELL": 6, "VIBE": 6, "BASS": 12, "SYNTH": 10, "STRNG": 6, "ORGAN": 8}
MODES = ["EP", "BELL", "VIBE", "BASS", "SYNTH", "STRNG", "ORGAN"]
RENAME = {"Velvet Bounce EP": "VELVET EP"}

def time_table():
    t = (ROOT / "build/gen/felucca_tables.h").read_text()
    body = re.search(r"TIME_MS_X10\[128\] = \{(.*?)\};", t, re.S).group(1)
    return [int(x) / 10 for x in re.findall(r"\d+", body)]
TIME = time_table()
def ms(v):                       # milliseconds -> the nearest ATK / DEC / REL value
    return min(range(128), key=lambda i: abs(TIME[i] - v))
def u(x):                        # 0..1 -> 0..127
    return max(0, min(127, int(round(x * 127))))

def bars_of(drawbars):           # the BARS value whose morphed registration is nearest the sound's nine drawbars
    best, at = 1e9, 0
    for b in range(128):
        x = b * 7; lo = x // 127; fr = (x - lo * 127) / 127; hi = min(lo + 1, 7)
        err = sum((REG[lo][i] * (1 - fr) + REG[hi][i] * fr - drawbars[i] * 8) ** 2 for i in range(9))
        if err < best: best, at = err, b
    return at

def convert(p):
    v, c, o, e = p["values"], p["character"], p["organ"], p["engine"]
    tone, drive, space, decay, motion = v[1], v[2], v[3], v[5], v[6]
    dec = ms(120 + decay * 700)
    if e == 0:
        mode = ["EP", "BELL", "VIBE"][int(p["keysStyle"])]
        E = [u(v[9]), 64, 64]
        env = [ms(4 if mode == "EP" else 1.5), dec, 76 if mode == "EP" else 127, ms(v[10])]
        mono, chorus = 0, 0
    elif e == 1 and p["fm"][0] < .5:
        mode = "BASS"; ladder = c[3] > .5
        E = [u(c[4]) if ladder else 0, u(c[5]) if ladder else 0, 64]
        env = [ms(4), dec, 91, ms(70 + decay * 650)]
        mono, chorus = int(v[7] > 0), 0
    elif e == 2:
        strings = c[0] > .5; mode = "STRNG" if strings else "SYNTH"
        E = [u(v[11]), u(v[12]), 64]
        env = [ms(c[1]), dec, 108, ms(c[2])] if strings else [ms(18), dec, 91, ms(70 + decay * 650)]
        mono, chorus = 0, 40 if strings else 0
    elif e == 4:
        mode = "ORGAN"
        E = [bars_of(o[1:10]), u(o[10]), u(o[11])]
        env = [ms(3), dec, 127, ms(o[12])]
        mono, chorus = 0, int(round(o[13] * 80))
    else:
        return None
    name = RENAME.get(p["name"], p["name"]).upper().replace("’", "'")
    name = re.sub(r"^(KEYS|BASS|SYNTH|SYNTHS|ORGAN|STRINGS) - ", "", name)
    name = re.sub(r"[^A-Z0-9 '+\-.]", "", name).strip()
    name = re.sub(r" +", " ", name.replace(" - ", " "))
    words = name.split(" ")
    while len(" ".join(words)) > 12 and len(words) > 1 and len(" ".join(words[:-1])) >= 6:   # 12 characters fit the screen
        words = words[:-1]
    clean = len(" ".join(words)) <= 12
    name = " ".join(words)[:12].strip()
    row = [MODES.index(mode), u(tone), u(decay), u(motion)] + E + [u(drive)]
    return mode, name, row, env, mono, [0, chorus, 0, min(127, int(round(space * 100)))], clean

def main():
    sounds = json.loads(Path(sys.argv[1]).read_text())
    out = Path(sys.argv[2]) if len(sys.argv) > 2 else ROOT / "firmware/src/velvet_presets.h"
    left, seen, rows = dict(QUOTA), set(), {m: [] for m in MODES}
    for want_clean in (True, False):                  # names that fit whole first, cut ones only to fill a quota
        for p in sounds:
            r = convert(p)
            if not r or r[6] != want_clean: continue
            mode, name = r[0], r[1]
            if name in seen or left[mode] == 0: continue
            seen.add(name); left[mode] -= 1; rows[mode].append(r)
    L = ["/* SPDX-License-Identifier: GPL-3.0-only */",
         "/* Generated by tools/gen_velvet_presets.py from the VELVET MOTION 0.56 factory library: do not edit.",
         " * {name, {MODE, TONE, DCY, MOVE, E4, E5, E6, WARM}, {ATK, DEC, SUS, REL}, filter env, mono, FX(dist, chorus, delay, reverb)} */",
         "static const preset_t VELVET_PRESETS[] = {"]
    for m in MODES:
        for (_, name, row, env, mono, fx, _c) in rows[m]:
            L.append('    {"%s", {%s}, {%s}, 0, %d, FX(%s)},' % (name, ", ".join(map(str, row)), ", ".join(map(str, env)), mono, ", ".join(map(str, fx))))
    L.append("};")
    first = lambda m: sum(len(rows[x]) for x in MODES[:MODES.index(m)])
    L.append("#define VLV_DEF_BASS %du   /* the first BASS and the first STRNG sound: parts 2 and 3 at power-on */" % first("BASS"))
    L.append("#define VLV_DEF_PAD %du" % first("STRNG"))
    out.write_text("\n".join(L) + "\n")
    print("velvet presets:", {m: len(rows[m]) for m in MODES}, "->", out)

if __name__ == "__main__":
    main()
