"""VELVET MOTION chord progressions (*.vmprogression) -> firmware/src/velvet_progs.h

    tools/gen_velvet_progs.py DIR [OUT.h]

A progression file holds up to eight chords of up to five notes ("individualNotes": per chord an on flag, five
notes, -1 = none). A sequencer step holds four notes, so a five-note chord drops its fifth (the tone seven
semitones above the lowest; else its second-lowest tone): root, third, seventh and ninth stay.
"""
import json, re, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]

def chord4(notes):
    notes = sorted(set(int(n) for n in notes if n >= 0))
    while len(notes) > 4:
        fifth = [n for n in notes[1:] if (n - notes[0]) % 12 == 7]
        notes.remove(fifth[0] if fifth else notes[1])
    return notes

def main():
    src = Path(sys.argv[1]); out = Path(sys.argv[2]) if len(sys.argv) > 2 else ROOT / "firmware/src/velvet_progs.h"
    rows = []
    for f in sorted(src.glob("*.vmprogression")):
        d = json.loads(f.read_text()); v = d.get("individualNotes")
        if not v: continue                     # an arpeggio / strum setting without written-out chords
        chords = [chord4(v[i + 1:i + 6]) for i in range(0, len(v), 7) if v[i] > 0]
        chords = [c for c in chords if c][:8]
        if len(chords) < 2: continue
        name = re.sub(r"[^A-Z0-9 \-]", "", d["name"].upper())
        name = name.replace("MAJOR", "MAJ").replace("DORIAN 2", "DOR 2").replace("SOULFUL", "SOUL").replace(" SEVENTHS", "")
        words = name.split()
        while len(" ".join(words)) > 12 and len(words) > 1: words = words[:-1]
        rows.append((" ".join(words)[:12], chords))
    L = ["/* SPDX-License-Identifier: GPL-3.0-only */",
         "/* Generated by tools/gen_velvet_progs.py from VELVET MOTION's progression files: do not edit.",
         " * A progression: its name, its number of chords, and each chord's notes (0 = none), lowest first. */",
         "#define VLV_PROG_CHORDS 8u",
         "static const struct { const char *name; uint8_t n, note[VLV_PROG_CHORDS][4]; } VLV_PROGS[] = {"]
    for name, chords in rows:
        cs = ", ".join("{%s}" % ", ".join(str(n) for n in (c + [0, 0, 0, 0])[:4]) for c in chords)
        L.append('    {"%s", %d, {%s}},' % (name, len(chords), cs))
    L += ["};", "#define VLV_NPROG ((uint32_t)(sizeof VLV_PROGS / sizeof VLV_PROGS[0]))"]
    out.write_text("\n".join(L) + "\n"); print("progressions:", len(rows), "->", out)
    for name, chords in rows: print("  %-12s %d chords" % (name, len(chords)))

if __name__ == "__main__":
    main()
